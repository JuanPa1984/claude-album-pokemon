const LEGENDARY = new Set([144, 145, 146, 150, 151, 243, 244, 245, 249, 250, 251]);
const RARE = new Set([3, 6, 9, 25, 94, 130, 131, 143, 149, 154, 157, 160, 196, 197, 212, 248]);

export function rarityFor(pokedexNumber: number): Rarity {
  if (LEGENDARY.has(pokedexNumber)) return 'LEGENDARY';
  if (RARE.has(pokedexNumber)) return 'RARE';
  return 'COMMON';
}

export function spriteUrl(pokedexNumber: number): string {
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/${pokedexNumber}.png`;
}
